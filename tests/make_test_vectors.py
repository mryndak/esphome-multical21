"""Generates synthetic MULTICAL 21 telegrams for the unit tests.

The frames follow the exact structure of real MULTICAL 21 C1 telegrams, but use
a made-up meter id and key, so no real meter data ends up in the repository.

    python tests/make_test_vectors.py > tests/test_vectors.h
"""

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

METER_ID = 0x12345678
KEY = bytes(range(16))
MANUFACTURER = bytes([0x2D, 0x2C])  # Kamstrup
VERSION, DEVICE_TYPE = 0x1B, 0x16  # cold water
FORMAT = bytes.fromhex("02ff2004134413615b6167")


def crc16(data: bytes) -> int:
    crc = 0
    for byte in data:
        crc ^= byte << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x3D65) & 0xFFFF if crc & 0x8000 else (crc << 1) & 0xFFFF
    return crc ^ 0xFFFF


def records(info: int, total: int, target: int, flow: int, ambient: int) -> bytes:
    return (
        bytes.fromhex("02ff20") + info.to_bytes(2, "little")
        + bytes.fromhex("0413") + total.to_bytes(4, "little")
        + bytes.fromhex("4413") + target.to_bytes(4, "little")
        + bytes.fromhex("615b") + (flow & 0xFF).to_bytes(1, "little")
        + bytes.fromhex("6167") + (ambient & 0xFF).to_bytes(1, "little")
    )


def full_payload(*values) -> bytes:
    return b"\x78" + records(*values)


def compact_payload(*values) -> bytes:
    info, total, target, flow, ambient = values
    data = (info.to_bytes(2, "little") + total.to_bytes(4, "little") + target.to_bytes(4, "little")
            + bytes([flow & 0xFF, ambient & 0xFF]))
    return (b"\x79" + crc16(FORMAT).to_bytes(2, "little")
            + crc16(records(*values)).to_bytes(2, "little") + data)


def frame(payload: bytes, access: int, key: bytes = KEY, meter_id: int = METER_ID) -> bytes:
    address = meter_id.to_bytes(4, "little") + bytes([VERSION, DEVICE_TYPE])
    cc = 0x20
    session = (0x2157BA00 | access).to_bytes(4, "little")  # top bits 001 = AES-128-CTR
    iv = MANUFACTURER + address + bytes([cc]) + session + b"\x00\x00\x00"
    plain = crc16(payload).to_bytes(2, "little") + payload
    encrypted = Cipher(algorithms.AES(key), modes.CTR(iv)).encryptor().update(plain)
    body = bytes([0x44]) + MANUFACTURER + address + bytes([0x8D, cc, access]) + session + encrypted
    return bytes([len(body)]) + body


def add_format_a_crcs(stripped: bytes) -> bytes:
    out = stripped[:10] + crc16(stripped[:10]).to_bytes(2, "big")
    rest = stripped[10:]
    for i in range(0, len(rest), 16):
        block = rest[i:i + 16]
        out += block + crc16(block).to_bytes(2, "big")
    return out


def c_array(name: str, data: bytes) -> str:
    body = ", ".join(f"0x{b:02X}" for b in data)
    return f"static const uint8_t {name}[] = {{{body}}};"


VALUES = (0x0000, 123456, 120000, 12, 21)
ALARM_VALUES = (0x0404, 123460, 120000, 11, 20)  # LEAK now, leak during the last 1-8 hours

vectors = {
    "FULL_FRAME": frame(full_payload(*VALUES), 0x10),
    "COMPACT_FRAME": frame(compact_payload(*VALUES), 0x11),
    "COMPACT_ALARM_FRAME": frame(compact_payload(*ALARM_VALUES), 0x12),
    "NEGATIVE_TEMP_FRAME": frame(full_payload(0, 123456, 120000, 2, -5), 0x13),
    "OTHER_METER_FRAME": frame(full_payload(*VALUES), 0x14, meter_id=0x87654321),
    "WRONG_KEY_FRAME": frame(full_payload(*VALUES), 0x15, key=bytes(16)),
}
vectors["FULL_FRAME_RAW_A"] = add_format_a_crcs(vectors["FULL_FRAME"])

print("#pragma once")
print("// Generated by tests/make_test_vectors.py - do not edit by hand.")
print("#include <cstdint>")
print(f"static const uint32_t TEST_METER_ID = 0x{METER_ID:08X};")
print(c_array("TEST_KEY", KEY))
for name, data in vectors.items():
    print(c_array(name, data))
